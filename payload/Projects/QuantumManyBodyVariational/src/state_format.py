"""Public entry point for the shared-source correlator format."""

from __future__ import annotations

import hashlib
import re
from dataclasses import replace
from functools import cache
from importlib.metadata import version
from pathlib import Path

from .correlator_energy import evaluate_energy
from .correlator_hybrid_branch import BranchMath
from .state_format_eval import Evaluator
from .state_format_ir import FormatError, LANGUAGE_VERSION
from .state_format_lean import emit_lean
from .state_format_math import MATH_SOURCE
from .state_format_parse import parse


_MATH_IMPORT = re.compile(r"\A(?:[ \t]*(?:#[^\r\n]*)?\r?\n)*use math[ \t]*(?:\r?\n|$)")
_MATH_NAMES = frozenset(re.findall(r"(?m)^def (\w+)\(", MATH_SOURCE))
_MATH_DIGEST = hashlib.sha256(MATH_SOURCE.encode("utf-8")).hexdigest()


@cache
def runtime_sha256() -> str:
    """Bind generated Python to its evaluator, parser, and rational rules."""
    root = Path(__file__).parent
    names = (
        "state_format.py", "state_format_parse.py", "state_format_ir.py",
        "state_format_eval.py", "state_format_math.py", "state_format_numeric.py",
        "correlator_energy.py", "correlator_float_guard.py",
        "correlator_hybrid_branch.py", "correlator_rational_math.py", "rational_text.py",
    )
    digest = hashlib.sha256()
    for name in names:
        digest.update(name.encode("ascii"))
        digest.update(hashlib.sha256((root / name).read_bytes()).digest())
    digest.update(f"mpmath={version('mpmath')}".encode("utf-8"))
    return digest.hexdigest()


def _prune_library(program):
    by_name = {fn.name: fn for fn in program.functions}
    active = set(by_name) - _MATH_NAMES
    work = [by_name[name].body for name in active]
    while work:
        expr = work.pop()
        if expr.op == "call" and expr.value not in active:
            active.add(expr.value)
            work.append(by_name[expr.value].body)
        work.extend(expr.args)
    return replace(program, functions=tuple(fn for fn in program.functions if fn.name in active))


def source_from_markdown(text: str) -> str:
    """Extract the unique state program in a constructor handoff."""
    programs = re.findall(r"(?ms)^ *```state[ \t]*\r?\n(.*?)^ *```[ \t]*(?:\r?\n|$)", text)
    if len(programs) != 1:
        raise FormatError("A Markdown handoff must contain exactly one ```state code block")
    return programs[0]


class StateProgram:
    """One typed definition used for both the Lean and numerical artifacts."""

    def __init__(self, source: str, dimension: int, qubits_per_cell: int, *,
                 bits: int = 40, terms: int = 32, precision_bits: int = 40):
        if type(source) is not str:
            raise FormatError("State source must be text")
        self.source = source
        self.source_sha256 = hashlib.sha256(source.encode("utf-8")).hexdigest()
        match = _MATH_IMPORT.match(source)
        self.uses_math = match is not None
        if match:
            start = source.rfind("use math", 0, match.end())
            source = source[:start] + "\n" + source[match.end():] + "\n\n" + MATH_SOURCE
        program = parse(source, dimension, qubits_per_cell, bits=bits, terms=terms)
        self.program = _prune_library(program) if self.uses_math else program
        self.precision_bits = precision_bits
        self.evaluator = Evaluator(self.program, precision_bits=precision_bits)

    def evaluate(self, word) -> float:
        return self.evaluator.evaluate(word)

    def lean_source(self) -> str:
        header = f"-- {LANGUAGE_VERSION}; state source SHA256 {self.source_sha256}\n"
        return header + emit_lean(self.program, namespace="GeneratedState")

    def python_source(self) -> str:
        """Generate an importable evaluator using the fixed state interpreter."""
        p = self.program
        return (
            f"# Generated by {LANGUAGE_VERSION}; source SHA256 {self.source_sha256}\n"
            "from src.state_format import StateProgram, runtime_sha256\n\n"
            f"if runtime_sha256() != {runtime_sha256()!r}:\n"
            "    raise RuntimeError('The state runtime has changed; regenerate both artifacts')\n\n"
            f"_program = StateProgram({self.source!r}, {p.dimension}, {p.qubits_per_cell}, "
            f"bits={p.bits}, terms={p.terms}, precision_bits={self.precision_bits})\n\n"
            "def f(word):\n"
            "    return _program.evaluate(word)\n"
        )

    def manifest(self) -> dict:
        p = self.program
        branch_math = BranchMath(bits=p.bits, terms=p.terms).manifest()
        result = {
            "language_version": LANGUAGE_VERSION,
            "source_sha256": self.source_sha256,
            "runtime_sha256": runtime_sha256(),
            "dimension": p.dimension,
            "qubits_per_cell": p.qubits_per_cell,
            "lean_target": "GeneratedState.ProofObligation",
            "branch_math": {
                key: branch_math[key] for key in ("policy", "rational_math", "branch_semantics", "limits")
            },
            "numeric_value_semantics": "exact_rational_when_available_otherwise_adaptive_mpmath_interval",
            "mpmath_version": version("mpmath"),
        }
        if p.limit:
            result["limit"] = {
                "approximation": p.limit[0],
                "cutoff": p.limit[1],
                "requested_truncation_bits": self.precision_bits,
                "tail_proof_checked_here": False,
            }
        if self.uses_math:
            result["math_library_sha256"] = _MATH_DIGEST
        return result

    def energy(self, task: dict) -> dict:
        """Evaluate the task's finite local terms with the same typed definition."""
        p = self.program
        if type(task) is not dict or (
            task.get("dimension"), task.get("qubits_per_cell")
        ) != (p.dimension, p.qubits_per_cell):
            raise FormatError("The task lattice must match the state program lattice")
        values = {}

        def expectation(word):
            if word not in values:
                values[word] = self.evaluator.evaluate_normalized(word)
            return values[word]

        result = evaluate_energy(task, expectation, f_manifest=self.manifest())
        result["preconditions"] = {
            "legality": "not_checked",
            "translation_invariance": "not_checked",
            "proof_checked_here": False,
        }
        result["distinct_words_evaluated"] = len(values)
        return result
